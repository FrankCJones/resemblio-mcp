@pytest.mark.asyncio
async def test_registered_protocol_retrieves_exact_complete_and_normalized_artifacts():
    """The Python MCP registration returns exact API artifacts for both selectors."""

    fixture = exact_export_fixture()["artifacts"]

    def handler(request: httpx.Request) -> httpx.Response:
        selection = request.url.params.get("selection")
        if selection == "complete":
            artifact = fixture["complete"]
        elif selection == "record":
            assert request.url.params.get_list("record") == [
                "component:buttons",
                "foundation:color-scale",
            ]
            artifact = fixture["records-normalized"]
        else:
            return httpx.Response(400, json={"error": "unexpected_selector"})
        return httpx.Response(200, json={"schema_version": 2, "data": artifact})

    client = make_client(handler)
    complete = await call_registered_export_tool(client, {"selection": "complete"})
    normalized = await call_registered_export_tool(client, {
        "selection": "record",
        "record_ids": [
            "foundation:color-scale",
            "component:buttons",
            "component:buttons",
        ],
    })

    assert complete.is_error is not True
    assert json.loads(complete.content[0].text) == fixture["complete"]
    assert normalized.is_error is not True
    assert json.loads(normalized.content[0].text) == fixture["records-normalized"]


@pytest.mark.asyncio
async def test_registered_protocol_marks_stable_api_error_and_preserves_body():
    """Server errors use MCP isError while retaining the stable API payload."""

    body = {"error": "unknown_record", "detail": "Every selected record must exist."}
    calls = {"count": 0}

    def handler(request: httpx.Request) -> httpx.Response:
        calls["count"] += 1
        return httpx.Response(400, json=body)

    result = await call_registered_export_tool(
        make_client(handler, max_retries=3),
        {"selection": "record", "record_ids": ["component:unknown"]},
    )

    assert result.is_error is True
    assert result.model_dump(by_alias=True)["isError"] is True
    assert json.dumps(body, separators=(",", ":")) in result.content[0].text
    assert calls["count"] == 1


@pytest.mark.asyncio
async def test_complete_export_retrieves_all_41_api_records_unchanged():
    """The complete selector reads the API artifact and returns its data object as-is."""
    records = canonical_records()
    artifact = export_artifact(records, "complete")

    def handler(request: httpx.Request) -> httpx.Response:
        assert request.url.path == "/v1/apple/exports/dtcg"
        assert request.url.params.get_list("selection") == ["complete"]
        return httpx.Response(200, json={"schema_version": 2, "data": artifact})

    result = await run_get_library_export(make_client(handler), {"selection": "complete"})
    assert result == artifact
    assert result["manifest"]["records"] == records
    assert result["manifest"]["selection"]["selected_record_count"] == 41


