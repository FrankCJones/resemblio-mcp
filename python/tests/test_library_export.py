@pytest.mark.asyncio
async def test_malformed_and_mixed_selectors_fail_before_http_request():
    """Invalid selector contracts fail closed with stable parser error codes."""
    fetches = {"count": 0}

    def handler(request: httpx.Request) -> httpx.Response:
        fetches["count"] += 1
        return httpx.Response(200, json={"schema_version": 2, "data": {}})

    client = make_client(handler)
    for value, code in (
        ({"selection": "complete", "record_ids": ["component:buttons"]}, "mixed_selection_contracts"),
        ({"selection": "classification", "classification": "other"}, "invalid_classification"),
        ({"selection": "record", "record_ids": []}, "missing_records"),
        ({"selection": "record", "record_ids": ["Buttons"]}, "invalid_record_id"),
    ):
        with pytest.raises(ValueError, match=code):
            await run_get_library_export(client, value)
    assert fetches["count"] == 0


